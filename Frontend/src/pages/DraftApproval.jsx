import { useEffect, useState } from 'react'
import { Link, useLocation, useSearchParams } from 'react-router-dom'
import {
  CheckCircle2,
  Loader2,
  Send,
  Sparkles,
  X,
} from 'lucide-react'

import Field from '../components/Field.jsx'
import ErrorMessage from '../components/ErrorMessage.jsx'
import useRequest from '../hooks/useRequest.js'
import {
  createDraft,
  decideDraft,
  getDraft,
  getErrorMessage,
  getGmailStatus,
} from '../api/axios.js'
import { useApp } from '../context/AppContext.jsx'

const tones = [
  'formal',
  'professional',
  'friendly',
  'casual',
  'persuasive',
  'apologetic',
  'urgent',
]

const lengths = ['short', 'medium', 'long']
const emojis = ['none', 'minimal', 'moderate', 'expressive']

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1)

const EMAIL_RE = /^[^@\s]+@[^@\s]+\.[^@\s]+$/

const splitList = (s = '') =>
  s.split(',').map((x) => x.trim()).filter(Boolean)

const validList = (s = '') =>
  splitList(s).every((email) => EMAIL_RE.test(email))

function GmailLink({ error }) {
  if (!/gmail/i.test(error || '')) return null

  return (
    <Link
      to="/settings"
      className="text-sm font-medium text-indigo-600 underline dark:text-indigo-400"
    >
      Open Gmail Settings
    </Link>
  )
}

const initialForm = {
  purpose: '',
  to: '',
  cc: '',
  bcc: '',
  recipient: '',
  sender_name: '',
  tone: 'professional',
  length: 'medium',
  emoji: 'none',
  language: 'English',
}

export default function DraftApproval() {
  const { state } = useLocation()
  const { addActivity } = useApp()

  // Dashboard ki Recent activity se aaya hua ?thread=<id>
  const [params, setParams] = useSearchParams()
  const threadId = params.get('thread')
  const [resuming, setResuming] = useState(false)

  const [f, setF] = useState(() => ({
    ...initialForm,
    purpose: state?.purpose || '',
    to: state?.to || '',
    recipient: state?.recipient || '',
    sender_name: state?.sender_name || '',
    tone: state?.tone || 'professional',
    length: state?.length || 'medium',
    emoji: state?.emoji || 'none',
    language: state?.language || 'English',
  }))

  // Incoming generated content is not yet a Gmail draft.
  const [draft, setDraft] = useState(null)
  const [edit, setEdit] = useState({
    subject: '',
    body: '',
  })

  const [done, setDone] = useState(null)
  const [sentFrom, setSentFrom] = useState('')
  const [gmail, setGmail] = useState(null)

  const drafting = useRequest(createDraft)
  const deciding = useRequest(decideDraft)

  const set = (key) => (e) => {
    setF((prev) => ({
      ...prev,
      [key]: e.target.value,
    }))
  }

  // Load Gmail status.
  useEffect(() => {
    getGmailStatus()
      .then(setGmail)
      .catch(() => {})
  }, [])

  // Load email generated by EmailGenerator.jsx.
  useEffect(() => {
    if (!state) return

    setF((prev) => ({
      ...prev,
      purpose: state.purpose ?? prev.purpose,
      to: state.to ?? prev.to,
      recipient: state.recipient ?? prev.recipient,
      sender_name: state.sender_name ?? prev.sender_name,
      tone: state.tone ?? prev.tone,
      length: state.length ?? prev.length,
      emoji: state.emoji ?? prev.emoji,
      language: state.language ?? prev.language,
    }))

    if (state.subject || state.body) {
      // Reset any previous draft so content cannot be mixed up.
      setDraft(null)
      setEdit({
        subject: state.subject || '',
        body: state.body || '',
      })
      setDone(null)
      drafting.reset()
      deciding.reset()
    }
  }, [state])

  // Recent activity se pending draft wapas kholo (?thread=<id>)
  useEffect(() => {
    if (!threadId) return
    if (draft?.thread_id === threadId) return // already loaded

    let cancelled = false
    setResuming(true)
    deciding.reset()

    getDraft(threadId)
      .then((res) => {
        if (cancelled) return
        setDraft(res)
        setEdit({ subject: res.subject || '', body: res.body || '' })
        setF((prev) => ({ ...prev, to: res.to || prev.to }))
        setDone(null)
      })
      .catch((e) => {
        if (cancelled) return
        drafting.fail(
          e?.response?.status === 404
            ? 'Ye draft expire ho gaya ya pehle hi process ho chuka hai. Naya draft banao.'
            : getErrorMessage(e)
        )
        setParams({}, { replace: true }) // galat/purane thread URL se hata do
      })
      .finally(() => {
        if (!cancelled) setResuming(false)
      })

    return () => {
      cancelled = true
    }
  }, [threadId])

  const gmailMissing = gmail && !gmail.connected

  const changed =
    draft &&
    (edit.subject !== draft.subject ||
      edit.body !== draft.body)

  // Create a real backend/Gmail draft.
  const makeDraft = async (e) => {
    e?.preventDefault()

    if (!f.purpose.trim() && !edit.body.trim()) {
      return drafting.fail('Enter the email purpose or provide an email body.')
    }

    if (!splitList(f.to).length || !validList(f.to)) {
      return drafting.fail('Enter a valid recipient email address.')
    }

    if (!validList(f.cc)) {
      return drafting.fail('One or more CC email addresses are invalid.')
    }

    if (!validList(f.bcc)) {
      return drafting.fail('One or more BCC email addresses are invalid.')
    }

    deciding.reset()

    // If content came from EmailGenerator, use it.
    // Otherwise, ask the backend to generate the draft.
    const payload = {
      ...f,
      purpose: f.purpose.trim(),
      to: f.to.trim(),
      recipient: f.recipient.trim(),
      sender_name: f.sender_name.trim(),
      language: f.language.trim() || 'English',
      cc: f.cc.trim() || null,
      bcc: f.bcc.trim() || null,
      ...(edit.subject.trim() && edit.body.trim()
        ? {
            subject: edit.subject.trim(),
            body: edit.body.trim(),
          }
        : {}),
    }

    const res = await drafting.run(payload)

    if (res) {
      // The backend must return a real draft identifier.
      if (!res.thread_id) {
        drafting.fail(
          'The backend did not return thread_id. Check the createDraft API response.'
        )
        return
      }

      setDraft(res)
      setEdit({
        subject: res.subject || edit.subject,
        body: res.body || edit.body,
      })
      setDone(null)
      if (threadId) setParams({}, { replace: true }) // purana ?thread= hata do
    }
  }

  const approve = async () => {
    if (!draft?.thread_id) {
      return deciding.fail('Create a draft before approving it.')
    }

    const payload = changed
      ? {
          thread_id: draft.thread_id,
          action: 'edit',
          subject: edit.subject.trim(),
          body: edit.body.trim(),
        }
      : {
          thread_id: draft.thread_id,
          action: 'approve',
        }

    const res = await deciding.run(payload)

    if (res) {
      setSentFrom(res.from || '')
      addActivity('Approved Send', draft.to, 'Sent')
      setDone('sent')
      if (threadId) setParams({}, { replace: true }) // refresh par dobara fetch na ho
    }
  }

  const reject = async () => {
    if (!draft?.thread_id) {
      return deciding.fail('Create a draft before rejecting it.')
    }

    const res = await deciding.run({
      thread_id: draft.thread_id,
      action: 'reject',
    })

    if (res) {
      addActivity('Draft', draft.to, 'Rejected')
      setDone('rejected')
      if (threadId) setParams({}, { replace: true })
    }
  }

  const startOver = () => {
    setF(initialForm)
    setDraft(null)
    setEdit({ subject: '', body: '' })
    setDone(null)
    setSentFrom('')
    if (threadId) setParams({}, { replace: true })

    drafting.reset()
    deciding.reset()

    getGmailStatus()
      .then(setGmail)
      .catch(() => {})
  }

  const hasIncomingContent =
    Boolean(edit.subject.trim() || edit.body.trim())

  // Approval panel tabhi dikhao jab draft ban chuka ho (ya result screen ho)
  const showReview = Boolean(draft || done)

  return (
    <div className="mx-auto max-w-6xl space-y-4">
      {gmailMissing && (
        <p className="rounded-lg bg-amber-50 p-3 text-sm text-amber-800 dark:bg-amber-500/10 dark:text-amber-300">
          Please connect Gmail before creating or sending a draft.{' '}
          <Link to="/settings" className="font-semibold underline">
            Connect Gmail
          </Link>
        </p>
      )}

      {resuming && (
        <p
          role="status"
          className="flex items-center gap-2 rounded-lg bg-blue-50 p-3 text-sm text-blue-800 dark:bg-blue-500/10 dark:text-blue-300"
        >
          <Loader2 className="h-4 w-4 animate-spin" />
          Loading your pending draft…
        </p>
      )}

      <div
        className={
          showReview
            ? 'grid gap-6 lg:grid-cols-2'
            : 'mx-auto max-w-3xl'
        }
      >
        {/* Step 1: form (always visible) */}
        <form onSubmit={makeDraft} className="card space-y-4" noValidate>
          {/* Content coming from Email Generator, before a draft exists */}
          {!draft && hasIncomingContent && (
            <div className="rounded-lg bg-blue-50 p-3 text-sm text-blue-800 dark:bg-blue-500/10 dark:text-blue-300">
              <p className="font-medium">Email received from Email Generator</p>
              <p className="mt-1 truncate">
                Subject: <b>{edit.subject || '(none)'}</b>
              </p>
              <p className="mt-1 text-xs opacity-80">
                Check the recipient below, then create the draft.
              </p>
            </div>
          )}

          <Field
            id="purpose"
            as="textarea"
            rows={3}
            label="Purpose or topic"
            placeholder="Request 2 days leave next week"
            value={f.purpose}
            onChange={set('purpose')}
          />

          <div className="grid gap-4 sm:grid-cols-2">
            <Field
              id="to"
              label="To (email)"
              type="email"
              placeholder="recipient@example.com"
              value={f.to}
              onChange={set('to')}
            />

            <Field
              id="recipient"
              label="Recipient name (optional)"
              placeholder="Amit"
              value={f.recipient}
              onChange={set('recipient')}
            />

            <Field
              id="sender_name"
              label="Your name (optional)"
              placeholder="Your account name"
              value={f.sender_name}
              onChange={set('sender_name')}
            />

            <Field
              id="language"
              as="select"
              label="Language"
              value={f.language}
              onChange={set('language')}
            >
              <option value="English">English</option>
              <option value="Hindi">Hindi</option>
            </Field>

            <Field
              id="tone"
              as="select"
              label="Tone"
              value={f.tone}
              onChange={set('tone')}
            >
              {tones.map((t) => (
                <option key={t} value={t}>
                  {cap(t)}
                </option>
              ))}
            </Field>

            <Field
              id="length"
              as="select"
              label="Length"
              value={f.length}
              onChange={set('length')}
            >
              {lengths.map((t) => (
                <option key={t} value={t}>
                  {cap(t)}
                </option>
              ))}
            </Field>

            <Field
              id="emoji"
              as="select"
              label="Emoji"
              value={f.emoji}
              onChange={set('emoji')}
            >
              {emojis.map((t) => (
                <option key={t} value={t}>
                  {cap(t)}
                </option>
              ))}
            </Field>
          </div>

          <ErrorMessage message={drafting.error} />
          <GmailLink error={drafting.error} />

          <button
            type="submit"
            className="btn-primary"
            disabled={drafting.loading || Boolean(gmailMissing)}
          >
            {drafting.loading ? (
              <Loader2 className="h-4 w-4 animate-spin" />
            ) : (
              <Sparkles className="h-4 w-4" />
            )}
            {drafting.loading
              ? 'Creating draft…'
              : draft
                ? 'Regenerate draft'
                : hasIncomingContent
                  ? 'Create draft from generated email'
                  : 'Generate draft'}
          </button>
        </form>

        {/* Step 2: review and approval (only after a draft exists) */}
        {showReview && (
          <section className="card space-y-4" aria-live="polite">
            <h2 className="font-semibold text-slate-900 dark:text-white">
              Draft for approval
            </h2>

            {done ? (
              <>
                <div
                  role="status"
                  className="flex gap-2 rounded-lg border border-emerald-200 bg-emerald-50 p-3 text-sm text-emerald-700 dark:border-emerald-500/30 dark:bg-emerald-500/10 dark:text-emerald-300"
                >
                  <CheckCircle2 className="h-4 w-4 shrink-0" />
                  {done === 'sent'
                    ? `Email sent${sentFrom ? ` from ${sentFrom}` : ''} to ${draft?.to}.`
                    : 'Draft rejected. Nothing was sent.'}
                </div>

                <button
                  type="button"
                  className="btn-primary"
                  onClick={startOver}
                >
                  Write another
                </button>
              </>
            ) : (
              <>
                <p className="rounded-lg bg-amber-50 p-3 text-sm text-amber-800 dark:bg-amber-500/10 dark:text-amber-300">
                  Review your email. Nothing will be sent until you approve it.
                </p>

                <p className="text-sm">
                  {gmail?.email && (
                    <>
                      From: <b>{gmail.email}</b> ·{' '}
                    </>
                  )}
                  To: <b>{draft?.to || f.to || 'Not specified'}</b>
                </p>

                <Field
                  id="out-subject"
                  label="Subject"
                  value={edit.subject}
                  onChange={(e) =>
                    setEdit((prev) => ({
                      ...prev,
                      subject: e.target.value,
                    }))
                  }
                />

                <Field
                  id="out-body"
                  as="textarea"
                  rows={12}
                  label="Email body"
                  value={edit.body}
                  onChange={(e) =>
                    setEdit((prev) => ({
                      ...prev,
                      body: e.target.value,
                    }))
                  }
                />

                <ErrorMessage message={deciding.error} />
                <GmailLink error={deciding.error} />

                <div className="flex flex-wrap gap-3">
                  <button
                    type="button"
                    className="btn-primary"
                    onClick={approve}
                    disabled={
                      deciding.loading ||
                      !edit.subject.trim() ||
                      !edit.body.trim()
                    }
                  >
                    {deciding.loading ? (
                      <Loader2 className="h-4 w-4 animate-spin" />
                    ) : (
                      <Send className="h-4 w-4" />
                    )}
                    {deciding.loading
                      ? 'Sending…'
                      : changed
                        ? 'Approve edited and send'
                        : 'Approve and send'}
                  </button>

                  <button
                    type="button"
                    className="btn-secondary"
                    onClick={reject}
                    disabled={deciding.loading}
                  >
                    <X className="h-4 w-4" />
                    Reject
                  </button>
                </div>
              </>
            )}
          </section>
        )}
      </div>
    </div>
  )
}